/**
 * ClusterNode - ReactFlow node component for semantic clusters
 *
 * Displays a cluster as a "Hub" (circular node) to better visualize it as a center of gravity.
 * Shows member count badge and expands on double-click.
 */

import React, { memo, useState, useCallback, useRef, useEffect } from 'react';
import PropTypes from 'prop-types';
import { Handle, Position, NodeToolbar } from '@xyflow/react';
import {
  Layers,
  FolderPlus,
  FolderInput,
  Download,
  ExternalLink,
  Pencil,
  Search,
  Sparkles,
  Tag
} from 'lucide-react';
import { IconButton } from '../ui';
import { sanitizeSemanticTerms } from '../../utils/semanticTerms';

// Hub sizing constants
const HUB_SIZE = {
  MIN_DIAMETER: 112,
  MAX_DIAMETER: 176,
  LOG_SCALE_DIVISOR: 2.5
};

const ClusterNode = memo(({ data, selected }) => {
  const [isEditingLabel, setIsEditingLabel] = useState(false);
  const [editedLabel, setEditedLabel] = useState('');
  const labelInputRef = useRef(null);
  const focusTimerRef = useRef(null);

  const isExpanded = data?.expanded || false;
  const memberCount = data?.memberCount || 0;
  const label = data?.label || 'Cluster';
  const isAutoGenerated = data?.isAutoGenerated !== false;
  const rawConfidence = data?.confidence || 'low';
  const confidence = ['high', 'medium', 'low'].includes(rawConfidence) ? rawConfidence : 'low';
  const topTerms = sanitizeSemanticTerms(data?.topTerms || data?.commonTags || [], {
    maxTerms: 3,
    minLength: 2
  });

  // Actions
  const {
    onCreateSmartFolder,
    onMoveAllToFolder,
    onExportFileList,
    onExpand,
    onOpenAllFiles,
    onSearchWithinCluster,
    onRenameCluster,
    onTagCluster
  } = data || {};

  const handleExpandClick = useCallback(
    (e) => {
      e.stopPropagation();
      const clusterId = data?.id || data?.clusterId;
      if (clusterId && onExpand) {
        onExpand(clusterId);
      }
    },
    [onExpand, data]
  );

  const handleMenuAction = useCallback((action) => action?.(data), [data]);

  useEffect(
    () => () => {
      if (focusTimerRef.current) {
        clearTimeout(focusTimerRef.current);
        focusTimerRef.current = null;
      }
    },
    []
  );

  // Label editing
  const handleStartEditLabel = useCallback(
    (e) => {
      e?.stopPropagation();
      setEditedLabel(label);
      setIsEditingLabel(true);
      if (focusTimerRef.current) {
        clearTimeout(focusTimerRef.current);
      }
      focusTimerRef.current = setTimeout(() => {
        focusTimerRef.current = null;
        labelInputRef.current?.focus();
      }, 50);
    },
    [label]
  );

  const handleSaveLabel = useCallback(() => {
    if (editedLabel.trim() && editedLabel !== label) {
      onRenameCluster?.({ ...data, newLabel: editedLabel.trim() });
    }
    setIsEditingLabel(false);
  }, [editedLabel, label, onRenameCluster, data]);

  const handleLabelKeyDown = useCallback(
    (e) => {
      e.stopPropagation();
      if (e.key === 'Enter') handleSaveLabel();
      else if (e.key === 'Escape') setIsEditingLabel(false);
    },
    [handleSaveLabel]
  );

  // Dynamic sizing based on member count
  const scaleFactor = Math.min(1, Math.log10(memberCount + 1) / HUB_SIZE.LOG_SCALE_DIVISOR);
  const diameter = Math.round(
    HUB_SIZE.MIN_DIAMETER + scaleFactor * (HUB_SIZE.MAX_DIAMETER - HUB_SIZE.MIN_DIAMETER)
  );
  const showTopTerms = topTerms.length > 0 && diameter >= 124;

  return (
    /* eslint-disable-next-line jsx-a11y/no-static-element-interactions -- graph-canvas pointer affordance; keyboard path tracked as U-T14 */
    <div
      // width/height are explicitly transitioned: the hub diameter grows with
      // member count, so the layout morph is intentional (bare `transition`
      // would exclude it). Everything else that changes state — scale, the
      // selected gradient, shadow/expand ring — is enumerated too (U-T13).
      className={`
        relative rounded-full border-2 shadow-md flex flex-col items-center justify-center overflow-visible
        transition-[width,height,transform,scale,background,box-shadow] duration-300 cursor-pointer
        ${selected ? 'scale-105 z-50' : 'hover:scale-[1.03] z-10'}
        ${isExpanded ? 'ring-4 ring-stratosort-accent/20' : ''}
      `}
      style={{
        width: `${diameter}px`,
        height: `${diameter}px`,
        background: selected
          ? 'linear-gradient(135deg, color-mix(in srgb, var(--color-stratosort-accent) 6%, white) 0%, color-mix(in srgb, var(--color-stratosort-accent) 12%, white) 100%)'
          : 'linear-gradient(135deg, color-mix(in srgb, var(--color-stratosort-accent) 3%, white) 0%, color-mix(in srgb, var(--color-stratosort-accent) 8%, white) 100%)',
        borderColor: 'var(--color-stratosort-accent)'
      }}
      onDoubleClick={handleExpandClick}
    >
      <NodeToolbar isVisible={selected} position={Position.Top} offset={20}>
        <div className="flex gap-1 bg-system-gray-100 shadow-xl rounded-lg border border-system-gray-200 p-1.5 animate-slide-up">
          {onOpenAllFiles && (
            <IconButton
              onClick={() => handleMenuAction(onOpenAllFiles)}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Open all files"
              aria-label="Open all files"
              icon={<ExternalLink className="w-4 h-4 text-stratosort-blue" />}
            ></IconButton>
          )}
          {onSearchWithinCluster && (
            <IconButton
              onClick={() => handleMenuAction(onSearchWithinCluster)}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Search within"
              aria-label="Search within"
              icon={<Search className="w-4 h-4 text-stratosort-indigo" />}
            ></IconButton>
          )}
          {onCreateSmartFolder && (
            <IconButton
              onClick={() => handleMenuAction(onCreateSmartFolder)}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Create Smart Folder"
              aria-label="Create Smart Folder"
              icon={<FolderPlus className="w-4 h-4 text-stratosort-accent" />}
            ></IconButton>
          )}
          {onMoveAllToFolder && (
            <IconButton
              onClick={() => handleMenuAction(onMoveAllToFolder)}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Move all"
              aria-label="Move all"
              icon={<FolderInput className="w-4 h-4 text-stratosort-blue" />}
            ></IconButton>
          )}
          {onExportFileList && (
            <IconButton
              onClick={() => handleMenuAction(onExportFileList)}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Export list"
              aria-label="Export list"
              icon={<Download className="w-4 h-4 text-stratosort-success" />}
            ></IconButton>
          )}
          {onTagCluster && (
            <IconButton
              onClick={() => handleMenuAction(onTagCluster)}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Tag files"
              aria-label="Tag files"
              icon={<Tag className="w-4 h-4 text-stratosort-purple" />}
            ></IconButton>
          )}
          {onRenameCluster && (
            <IconButton
              onClick={handleStartEditLabel}
              size="sm"
              variant="ghost"
              className="h-7 w-7 text-system-gray-700 hover:bg-stratosort-warning/10"
              title="Rename"
              aria-label="Rename"
              icon={<Pencil className="w-4 h-4 text-system-gray-500" />}
            ></IconButton>
          )}
        </div>
      </NodeToolbar>

      {/* Central Target Handle - "Hidden" in center so edges radiate from middle */}
      <Handle
        type="target"
        position={Position.Left}
        style={{
          left: '50%',
          top: '50%',
          transform: 'translate(-50%, -50%)',
          opacity: 0,
          width: 10,
          height: 10,
          background: 'transparent',
          border: 'none',
          zIndex: 0
        }}
      />

      {/* Center Icon */}
      <div
        className={`p-2 rounded-full mb-1 ${selected ? 'bg-stratosort-accent/20 text-stratosort-accent' : 'bg-stratosort-accent/10 text-stratosort-accent'}`}
      >
        <Layers className="w-6 h-6" strokeWidth={1.5} />
      </div>

      {/* Label Area */}
      <div className="text-center px-4 w-full max-w-[82%] mx-auto relative z-10">
        {isEditingLabel ? (
          <input
            ref={labelInputRef}
            type="text"
            value={editedLabel}
            aria-label="Cluster label"
            onChange={(e) => setEditedLabel(e.target.value)}
            onBlur={handleSaveLabel}
            onKeyDown={handleLabelKeyDown}
            onClick={(e) => e.stopPropagation()}
            className="text-xs font-semibold text-center w-full bg-system-gray-100/70 border border-stratosort-accent/30 rounded-md focus:outline-none focus:border-stratosort-accent nodrag nopan"
          />
        ) : (
          <div
            className="cluster-node-label text-micro font-semibold text-system-gray-50 clamp-2 leading-tight break-normal group/label"
            title={label}
          >
            {label}
            {onRenameCluster && selected && (
              // Real button (not a click-only svg): keyboard users can Tab to
              // it once the node is selected, and it reveals on focus like it
              // does on hover. The toolbar's Rename IconButton remains the
              // primary keyboard path.
              <button
                type="button"
                aria-label="Rename cluster"
                onClick={handleStartEditLabel}
                className="absolute -right-2 top-0 opacity-0 group-hover/label:opacity-100 focus-visible:opacity-100 cursor-pointer nodrag nopan"
              >
                <Pencil className="w-3 h-3 text-system-gray-400" aria-hidden="true" />
              </button>
            )}
          </div>
        )}
      </div>

      {/* Top terms / why (kept inside the hub to avoid clipping) */}
      {showTopTerms && (
        <div
          className={`mt-0.5 px-4 max-w-[88%] mx-auto text-center text-[10px] leading-tight text-stratosort-accent font-medium break-normal ${diameter >= 140 ? 'clamp-2' : 'clamp-1'}`}
          title={`Shared terms: ${topTerms.join(', ')}`}
        >
          {topTerms.join(' • ')}
        </div>
      )}

      {/* Member Count Badge */}
      <div className="absolute -top-1 -right-1 bg-system-gray-100 border border-stratosort-accent/30 text-stratosort-accent text-micro font-semibold px-2 py-0.5 rounded-full shadow-sm flex items-center gap-1">
        <span>{memberCount}</span>
        {isAutoGenerated && <Sparkles className="w-2 h-2 text-stratosort-accent/70" />}
      </div>

      {/* Confidence Ring (Visual Indicator) */}
      <div
        className={`absolute inset-0 rounded-full border-2 opacity-30 pointer-events-none ${
          confidence === 'high'
            ? 'border-stratosort-success'
            : confidence === 'medium'
              ? 'border-stratosort-blue'
              : 'border-system-gray-300'
        }`}
        style={{ margin: '-6px' }}
        title={
          confidence === 'high'
            ? 'High confidence — AI generated a descriptive label from file content'
            : confidence === 'medium'
              ? 'Medium confidence — label derived from shared tags or categories'
              : 'Low confidence — label auto-generated from file count only'
        }
        aria-label={`Cluster confidence: ${confidence}`}
      />

      {/* Central Source Handle - "Hidden" in center */}
      <Handle
        type="source"
        position={Position.Right}
        style={{
          left: '50%',
          top: '50%',
          transform: 'translate(-50%, -50%)',
          opacity: 0,
          width: 10,
          height: 10,
          background: 'transparent',
          border: 'none',
          zIndex: 0
        }}
      />
    </div>
  );
});

ClusterNode.displayName = 'ClusterNode';

ClusterNode.propTypes = {
  data: PropTypes.shape({
    id: PropTypes.string,
    clusterId: PropTypes.oneOfType([PropTypes.string, PropTypes.number]),
    expanded: PropTypes.bool,
    memberCount: PropTypes.number,
    label: PropTypes.string,
    confidence: PropTypes.string,
    isAutoGenerated: PropTypes.bool,
    onCreateSmartFolder: PropTypes.func,
    onMoveAllToFolder: PropTypes.func,
    onExportFileList: PropTypes.func,
    onExpand: PropTypes.func,
    onOpenAllFiles: PropTypes.func,
    onSearchWithinCluster: PropTypes.func,
    onRenameCluster: PropTypes.func,
    onTagCluster: PropTypes.func
  }),
  selected: PropTypes.bool
};

export default ClusterNode;
