/**
 * Wrap PostScript bytes in the 30-byte DOS EPS binary header followed by a
 * fake TIFF preview section.
 */
function buildDosEps(postScript) {
  const preview = Buffer.from([0x49, 0x49, 0x2a, 0x00, 0x08, 0x00, 0x00, 0x00]);
  const header = Buffer.alloc(30);
  header.writeUInt8(0xc5, 0);
  header.writeUInt8(0xd0, 1);
  header.writeUInt8(0xd3, 2);
  header.writeUInt8(0xc6, 3);
  header.writeUInt32LE(30, 4); // PostScript offset
  header.writeUInt32LE(postScript.length, 8); // PostScript length
  header.writeUInt32LE(0, 12); // WMF offset
  header.writeUInt32LE(0, 16); // WMF length
  header.writeUInt32LE(30 + postScript.length, 20); // TIFF offset
  header.writeUInt32LE(preview.length, 24); // TIFF length
  header.writeUInt16LE(0xffff, 28); // checksum (unused)
  return Buffer.concat([header, postScript, preview]);
}

