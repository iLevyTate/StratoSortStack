/**
 * @jest-environment jsdom
 */
/**
 * Knowledge OS graph handlers that used to hide failures or act on the wrong
 * thing: the vector DB status subscription, cluster rename, triage moves,
 * oversized tag requests and the context menu on nodes that have no menu.
 * The store hooks and the graph's own state are mocked.
 */
import { renderHook, act } from '@testing-library/react';

const mockDispatch = jest.fn();
const mockState = {
  ui: { currentPhase: 'organize', viewMode: 'phased', isOrganizing: false, isLoading: false },
  files: {
    smartFolders: [],
    selectedFiles: [],
    fileStates: {},
    organizedFiles: [],
    organizedPathIndex: []
  },
  analysis: { isAnalyzing: false, results: [] }
};

jest.mock('../../../../src/renderer/store/hooks', () => ({
  useAppDispatch: jest.fn(() => mockDispatch),
  useAppSelector: jest.fn((selector) => selector(mockState))
}));

jest.mock('../../../../src/renderer/contexts/NotificationContext', () => ({
  useNotification: jest.fn(() => ({ showInfo: jest.fn(), addNotification: jest.fn() }))
}));

let mockNodes = [];
const mockSetNodes = jest.fn((update) => {
  mockNodes = typeof update === 'function' ? update(mockNodes) : update;
});

jest.mock('../../../../src/renderer/hooks', () => {
  const fallback = {};
  const actions = new Proxy(
    {},
    {
      get: (_target, name) => {
        if (name === 'setNodes') return mockSetNodes;
        if (!fallback[name]) fallback[name] = jest.fn();
        return fallback[name];
      }
    }
  );
  return {
    useGraphState: () => ({ nodes: mockNodes, edges: [], selectedNodeId: null, actions })
  };
});

jest.mock('../../../../src/renderer/components/search/hooks/useDuplicateBadgeScan', () => ({
  useDuplicateBadgeScan: jest.fn()
}));

jest.mock('../../../../src/renderer/utils/elkLayout', () => ({
  elkLayout: jest.fn(),
  cancelPendingLayout: jest.fn(),
  debouncedElkLayout: jest.fn(),
  smartLayout: jest.fn(),
  clusterRadialLayout: jest.fn(),
  clusterExpansionLayout: jest.fn(),
  LARGE_GRAPH_THRESHOLD: 1000
}));

import { useGraphTab } from '../../../../src/renderer/components/search/hooks/useGraphTab';

function renderGraphTab(overrides = {}) {
  const ref = () => ({ current: null });
  const setError = jest.fn();
  const refreshStats = jest.fn();
  const hook = renderHook(() =>
    useGraphTab({
      isOpen: false,
      activeTab: 'search',
      onClose: jest.fn(),
      query: '',
      setQuery: jest.fn(),
      defaultTopK: 10,
      stats: null,
      graphViewEnabled: false,
      setError,
      recommendationMap: {},
      sidebarSections: {},
      chatMessages: [],
      setChatMessages: jest.fn(),
      clusterActionRefs: ref(),
      handleMoveAllToFolderRef: ref(),
      layoutRequestCounterRef: { current: 0 },
      error: null,
      hasLoadedStats: false,
      refreshStats,
      organizationalHealthRef: ref(),
      ...overrides
    })
  );
  return { ...hook, setError, refreshStats };
}

const clusterNode = (id, label = 'Old name') => ({
  id,
  type: 'clusterNode',
  position: { x: 0, y: 0 },
  data: { kind: 'cluster', label, isAutoGenerated: true }
});

const labelOf = (id) => mockNodes.find((n) => n.id === id)?.data?.label;

describe('Knowledge OS graph handlers', () => {
  beforeEach(() => {
    mockNodes = [];
    mockSetNodes.mockClear();
    window.electronAPI = {};
  });

  afterEach(() => {
    delete window.electronAPI;
    delete window.api;
  });

  describe('vector DB status subscription', () => {
    test('subscribes through the preload bridge and unsubscribes on unmount', () => {
      const off = jest.fn();
      const onStatusChanged = jest.fn(() => off);
      const legacy = jest.fn();
      window.electronAPI = { vectorDb: { onStatusChanged } };
      window.api = { vectorDb: { onStatusChanged: legacy } };

      const { unmount } = renderGraphTab({ isOpen: true });

      expect(onStatusChanged).toHaveBeenCalledTimes(1);
      expect(onStatusChanged).toHaveBeenCalledWith(expect.any(Function));
      expect(legacy).not.toHaveBeenCalled();

      unmount();
      expect(off).toHaveBeenCalledTimes(1);
    });
  });

  describe('cluster rename', () => {
    test('puts the old name back and reports it when the backend refuses', async () => {
      mockNodes = [clusterNode('cluster:3')];
      const renameCluster = jest.fn(async () => ({ success: false, error: 'Cluster not found' }));
      window.electronAPI = { embeddings: { renameCluster } };
      const { result, setError } = renderGraphTab();

      await act(async () => {
        await result.current.handleRenameCluster({ id: 'cluster:3', newLabel: 'Taxes' });
      });

      expect(renameCluster).toHaveBeenCalledWith('cluster:3', 'Taxes');
      expect(labelOf('cluster:3')).toBe('Old name');
      expect(setError).toHaveBeenCalledWith(expect.stringContaining('Could not rename'));
    });

    test('keeps the new name when the backend accepts it', async () => {
      mockNodes = [clusterNode('cluster:3')];
      window.electronAPI = {
        embeddings: { renameCluster: jest.fn(async () => ({ success: true })) }
      };
      const { result, setError } = renderGraphTab();

      await act(async () => {
        await result.current.handleRenameCluster({ id: 'cluster:3', newLabel: 'Taxes' });
      });

      expect(labelOf('cluster:3')).toBe('Taxes');
      expect(setError).not.toHaveBeenCalled();
    });

    test('renames a regrouped group locally without calling the backend', async () => {
      mockNodes = [clusterNode('regroup:type:documents')];
      const renameCluster = jest.fn();
      window.electronAPI = { embeddings: { renameCluster } };
      const { result, setError } = renderGraphTab();

      await act(async () => {
        await result.current.handleRenameCluster({
          id: 'regroup:type:documents',
          newLabel: 'Paperwork'
        });
      });

      expect(renameCluster).not.toHaveBeenCalled();
      expect(labelOf('regroup:type:documents')).toBe('Paperwork');
      expect(setError).not.toHaveBeenCalled();
    });
  });

  describe('triage move', () => {
    const files = [{ path: 'C:\\in\\a.pdf' }, { path: 'C:\\in\\b.pdf' }];

    test('rejects when the batch fails, so the dialog does not close as if it worked', async () => {
      const organize = jest.fn(async () => ({ success: false, error: 'Destination is read-only' }));
      window.electronAPI = { files: { organize } };
      const { result, setError, refreshStats } = renderGraphTab();

      let thrown = null;
      await act(async () => {
        try {
          await result.current.handleMoveFiles(files, 'C:\\out');
        } catch (e) {
          thrown = e;
        }
      });

      expect(organize).toHaveBeenCalledTimes(1);
      expect(thrown).toBeInstanceOf(Error);
      expect(setError).toHaveBeenCalledTimes(1);
      expect(refreshStats).not.toHaveBeenCalled();
    });

    test('rejects on a partial move and keeps the file that failed in the list', async () => {
      const organize = jest.fn(async (ops) => ({
        success: true,
        successCount: 1,
        failCount: 1,
        results: [
          { success: true, source: ops[0].source, destination: ops[0].destination },
          { success: false, source: ops[1].source, error: 'File is in use' }
        ]
      }));
      window.electronAPI = { files: { organize } };
      const { result, setError } = renderGraphTab();
      act(() => result.current.setTriageFiles(files));

      let thrown = null;
      await act(async () => {
        try {
          await result.current.handleMoveFiles(files, 'C:\\out');
        } catch (e) {
          thrown = e;
        }
      });

      expect(thrown).toBeInstanceOf(Error);
      expect(setError).toHaveBeenCalledTimes(1);
      expect(result.current.triageFiles).toEqual([files[1]]);
    });

    test('resolves and clears the list when every file moved', async () => {
      const organize = jest.fn(async (ops) => ({
        success: true,
        results: ops.map((op) => ({ success: true, source: op.source }))
      }));
      window.electronAPI = { files: { organize } };
      const { result, setError, refreshStats } = renderGraphTab();
      act(() => result.current.setTriageFiles(files));

      await act(async () => {
        await result.current.handleMoveFiles(files, 'C:\\out');
      });

      expect(setError).not.toHaveBeenCalled();
      expect(refreshStats).toHaveBeenCalled();
      expect(result.current.triageFiles).toEqual([]);
    });
  });

  describe('context menu', () => {
    const rightClick = () => ({
      preventDefault: jest.fn(),
      stopPropagation: jest.fn(),
      clientX: 40,
      clientY: 40
    });

    test.each([
      ['folder', { id: 'folder:Invoices', type: 'folderNode', data: { kind: 'folder' } }],
      ['query', { id: 'query:tax', type: 'queryNode', data: { kind: 'query' } }],
      ['duplicate group', { id: 'dup:1', type: 'clusterNode', data: { kind: 'duplicate' } }]
    ])('does not open for a %s node', (_name, node) => {
      const { result } = renderGraphTab();

      act(() => result.current.onNodeContextMenu(rightClick(), node));

      expect(result.current.contextMenu).toBeNull();
    });

    test('opens for a file node', () => {
      const { result } = renderGraphTab();
      const node = { id: 'file:a', type: 'fileNode', data: { kind: 'file', path: 'C:\\a.pdf' } };

      act(() => result.current.onNodeContextMenu(rightClick(), node));

      expect(result.current.contextMenu).toMatchObject({ nodeId: 'file:a' });
    });
  });
});
